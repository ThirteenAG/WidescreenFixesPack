# Regenerates source/Shared/Console/PadButtonArtwork.hpp from the pad icon atlases in
# textures/RWGTA/ButtonIcons (64x64 cells, see resources/button-icons/generate.py).
# Each icon becomes one 16-byte aligned PS2 texture block, like PCButtonArtwork.hpp:
# PSMT8 pixels (64x64) followed by a CSM1-ordered 256-entry CT32 CLUT (0x80 = opaque).
from pathlib import Path
from PIL import Image
root = Path(__file__).resolve().parents[2]
atlases = root / 'textures/RWGTA/ButtonIcons'
# Atlas cells (resources/button-icons/generate.py order), named by the PS2 button in that position
cells = [('Cross', 0), ('Circle', 1), ('Square', 2), ('Triangle', 3), ('L1', 4), ('R1', 5), ('L2', 6), ('R2', 7),
         ('L3', 8), ('R3', 9), ('Select', 10), ('Start', 11), ('Up', 12), ('Down', 13), ('Left', 14), ('Right', 15),
         ('DPad', 16), ('LeftStick', 19), ('RightStick', 24)]
families = [('Xbox', 'pad_xbox.png'), ('Nintendo', 'pad_nintendo.png')]

def texture(im):
    q = im.quantize(colors=256, method=Image.Quantize.FASTOCTREE)
    pal = q.getpalette('RGBA'); pal = pal + [0] * (1024 - len(pal))
    clut = [0] * 256
    for j in range(256):
        r, g, b, a = pal[4 * j:4 * j + 4]
        csm = (j & ~24) | ((j & 8) << 1) | ((j & 16) >> 1)
        clut[csm] = r | g << 8 | b << 16 | ((a + 1) // 2) << 24
    return bytes(q.tobytes()) + b''.join(c.to_bytes(4, 'little') for c in clut)

out = ['#pragma once\n#include <cstdint>\n',
       '// Generated by resources/pad-buttons/generate.py. Do not edit.\n',
       '// Each texture: PSMT8 pixels (64x64) followed by a CSM1-ordered\n',
       '// 256-entry CT32 CLUT with PS2 alpha (0x80 opaque).\n',
       'namespace console::padbuttons {\n',
       'enum class Button : uint8_t { ' + ', '.join(n for n, _ in cells) + ', Count };\n',
       'enum class Family : uint8_t { ' + ', '.join(f for f, _ in families) + ', Count };\n',
       'constexpr unsigned size = 64, log2Size = 6;\n']
names = []
for family, file in families:
    atlas = Image.open(atlases / file).convert('RGBA')
    for name, cell in cells:
        im = atlas.crop(((cell % 8) * 64, (cell // 8) * 64, (cell % 8) * 64 + 64, (cell // 8) * 64 + 64))
        data = texture(im)
        ident = f'texture{family}{name}'
        names.append(ident)
        out.append(f'alignas(16) inline constexpr uint8_t {ident}[]={{\n')
        for o in range(0, len(data), 128):
            out.append(','.join(str(x) for x in data[o:o + 128]) + ',\n')
        out.append('};\n')
out.append('inline constexpr const uint8_t* artwork[unsigned(Family::Count)][unsigned(Button::Count)]={\n')
for f, (family, _) in enumerate(families):
    out.append('{' + ','.join(names[f * len(cells):(f + 1) * len(cells)]) + '},\n')
out.append('};\n}\n')
target = root / 'source/Shared/Console/PadButtonArtwork.hpp'
target.write_text(''.join(out), newline='\n')
print(target, target.stat().st_size, len(names), 'textures')
