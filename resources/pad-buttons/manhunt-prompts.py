"""Regenerate tutorial span metadata from an original Manhunt levels directory.

Only hashes, offsets and action numbers are emitted; game text is not redistributed.
Usage: python resources/pad-buttons/manhunt-prompts.py --game <game directory>
"""
from pathlib import Path
import argparse
import re
import struct

ROOT = Path(__file__).resolve().parents[2]
ALIASES = {
    0: ["Use", "Utiliser", "Benutzen", "Usa", "Usar"],
    1: ["Look Back", "Regarder derrière", "Umsehen", "Guarda dietro", "Mirar atrás"],
    2: ["Reload", "Recharger", "Nachladen", "Ricarica", "Recargar"],
    4: ["Inventory Swap", "Echanger objet", "Inventar blättern", "Scorri inventario", "Cambio inventario", "Inventory button", "touche Inventaire", "Inventar-Taste", "tasto Inventario"],
    6: ["Action", "Action 1", "Aktionstaste", "Azione", "Acción"],
    8: ["Action2", "Action 2", "Aktionstaste2", "Azione2", "Azione 2", "Acción2", "Acción 2"],
    18: ["Peek Left", "Coup d'oeil à gauche", "Links-Spähen", "Sbircia a sinistra", "Mirar izquierda"],
    19: ["Peek Right", "Coup d'oeil à droite", "Rechts-Spähen", "Sbircia a destra", "Mirar derecha"],
    20: ["Pause button", "touche Pause", "Pause-Taste", "tasto Pausa", "botón Pausa"],
    23: ["Run", "Courir", "Rennen", "Corri", "Correr"],
    24: ["Sneak", "Se faufiler", "Schleichen", "Furtivo", "Sigilo"],
    31: ["First Person", "1ère personne", "Ego-Ansicht", "Prima persona", "Primera persona", "Erste Person Ansichts Taste"],
    36: ["Inventory Up", "Inventaire haut", "Inventar auf", "Inventario su", "Inventario arriba"],
    37: ["Inventory Down", "Inventaire bas", "Inventar ab", "Inventario giù", "Inventario abajo"],
    14: ["keyboard", "clavier", "Tastatur", "tastiera", "teclado", "touche fléchée gauche ou droite", "même touche fléchée", "tasto freccia sinistra o destra", "tasto freccia nella stessa direzione"],
    38: ["mouse", "souris", "Maus", "ratón"],
    39: ["Inventory Item", "Objet inventaire", "Inventar Gegenstand", "Oggetto Inventario"],
}


def entries(path):
    data = path.read_bytes()
    size = struct.unpack_from("<I", data, 4)[0]
    base = size + 16
    for at in range(8, 8 + size, 12):
        offset = struct.unpack_from("<I", data, at)[0]
        key = data[at + 4:at + 12].split(b"\0")[0].decode("ascii")
        raw = data[base + offset:]
        end = next(i for i in range(0, len(raw) - 1, 2) if raw[i:i + 2] == b"\0\0")
        yield key, raw[:end].decode("utf-16-le")


def hash_text(text):
    value = 14695981039346656037
    for c in text.encode("utf-16-le"):
        value = ((value ^ c) * 1099511628211) & 0xFFFFFFFFFFFFFFFF
    return value


def build(game):
    paths = sorted((game / "levels").rglob("pc_*.gxt"))
    tutorials = {}
    for path in paths:
        if path.parent.parent.name == "GLOBAL" or re.search(r"_[fgis]$", path.stem):
            continue
        tutorials[path.parent] = {key for key, text in entries(path)
            if re.search(r"button|keyboard|mouse", text, re.I)}
    aliases = sorted(((word, action) for action, words in ALIASES.items() for word in words), key=lambda pair: -len(pair[0]))
    pattern = re.compile(r"(?<!\w)(?:" + "|".join(re.escape(word) for word, _ in aliases) + r")(?!\w)", re.I)
    actions = {word.casefold(): action for word, action in aliases}
    rows = {}
    for path in paths:
        keys = tutorials.get(path.parent, set())
        for key, text in entries(path):
            if key not in keys:
                continue
            spans = []
            selected_pattern = pattern
            if key == "H_PATR1" and path.stem.endswith("_g"):
                selected_pattern = re.compile(r"Links|Rechts")
            for match in selected_pattern.finditer(text):
                # The first words of some sentences are verbs, not control names.
                if match.start() == 0 and match[0].casefold() in ("use", "usa"):
                    continue
                offset = len(text[:match.start()].encode("utf-16-le")) // 2
                length = len(match[0].encode("utf-16-le")) // 2
                action = (18 if match[0] == "Links" else 19) if selected_pattern is not pattern else actions[match[0].casefold()]
                spans.append((offset, length, action))
            if spans:
                digest = hash_text(text)
                assert digest not in rows or rows[digest] == spans
                rows[digest] = spans
    output = ["#pragma once\n#include <cstdint>\n\n// Generated by resources/pad-buttons/manhunt-prompts.py.\nnamespace MHPrompts\n{\n",
        "    struct Span { uint64_t hash; uint16_t offset, length; uint8_t action; };\n",
        "    inline constexpr Span spans[] =\n    {\n"]
    for digest, spans in sorted(rows.items()):
        for offset, length, action in spans:
            output.append(f"        {{ 0x{digest:016X}ULL, {offset}, {length}, {action} }},\n")
    output.append("    };\n}\n")
    target = ROOT / "source/Manhunt.FusionFix/PromptSpans.hpp"
    target.write_text("".join(output), encoding="utf-8")
    print(f"{len(rows)} tutorial strings, {sum(map(len, rows.values()))} control references")


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--game", type=Path, required=True)
    build(parser.parse_args().game)
