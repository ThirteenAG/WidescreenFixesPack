# Builds the button icon atlases of the GTA III/VC/SA fixes (textures/RWGTA/ButtonIcons) and their table
# (source/Shared/RWGTA/ButtonIconAtlas.hpp) from the GTA IV Fusion Fix's pad icons and resources/pc-buttons.
# Usage: python resources/button-icons/generate.py <GTAIV.EFLC.FusionFix checkout>
# The outputs are checked in, so building the fixes doesn't need Python or Pillow.
import sys
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parents[2]
iv = Path(sys.argv[1] if len(sys.argv) > 1 else root.parent / 'GTAIV.EFLC.FusionFix') / 'textures/pc/textures/buttons_360.wtd'
keys_src = root / 'resources/pc-buttons'
out_dir = root / 'textures/RWGTA/ButtonIcons'
header = root / 'source/Shared/RWGTA/ButtonIconAtlas.hpp'

# Pad icons, by position (A = the bottom face button), in atlas order
pad_icons = [
    ('A', 'a_butt'), ('B', 'b_butt'), ('X', 'x_butt'), ('Y', 'y_butt'),
    ('LB', 'lb_butt'), ('RB', 'rb_butt'), ('LT', 'lt_butt'), ('RT', 'rt_butt'),
    ('LS', 'lstick_none'), ('RS', 'rstick_none'), ('Back', 'back_butt'), ('Start', 'start_butt'),
    ('DPadUp', 'dpad_up'), ('DPadDown', 'dpad_down'), ('DPadLeft', 'dpad_left'), ('DPadRight', 'dpad_right'),
    ('DPad', 'dpad_all'), ('DPadUpDown', 'dpad_updown'), ('DPadLeftRight', 'dpad_leftright'),
    ('LeftStick', 'lstick_all'), ('LeftStickUpDown', 'lstick_updown'), ('LeftStickLeftRight', 'lstick_leftright'),
    ('LeftStickUp', 'lstick_up'), ('LeftStickDown', 'lstick_down'),
    ('RightStick', 'rstick_all'), ('RightStickUpDown', 'rstick_updown'), ('RightStickLeftRight', 'rstick_leftright'),
]
pad_sets = [('xbox', ''), ('playstation', 'ps4_'), ('nintendo', 'switch_')]

# The game's key codes (RenderWare skeleton: ASCII for characters, 1000+ for the others) and their picture
special = ['ESC'] + ['F%d' % i for i in range(1, 13)] + ['INS', 'DEL', 'HOME', 'END', 'PGUP', 'PGDN', 'UP', 'DOWN', 'LEFT', 'RIGHT',
    'DIVIDE', 'TIMES', 'PLUS', 'MINUS', 'PADDEL', 'padend', 'paddown', 'padpgdn', 'padleft', 'pad5', 'NUMLOCK', 'padright',
    'padhome', 'padup', 'padpgup', 'padins', 'PADENTER', 'SCROLL', 'pause', 'BACKSP', 'TAB', 'CAPSLK', 'enter', 'SHIFT',
    'SHIFT', 'SHIFT', 'LCTRL', 'LCTRL', 'ALT', 'ALT', 'LWIN', 'RWIN', 'APPS']
keys = []
for i, name in enumerate(special):
    keys.append((1000 + i, name))
for c in range(ord('A'), ord('Z') + 1):
    keys.append((c, chr(c)))
for d in range(10):
    keys.append((ord('0') + d, str(d)))
keys += [(ord(' '), 'SPACEBAR'), (ord(';'), 'SEMICOLON'), (ord('='), 'EQUAL'), (ord(','), 'COMMA'), (ord('-'), 'MINUS'),
         (ord('.'), 'DOT'), (ord('`'), 'BACKTICK'), (ord('['), 'BRACKETL'), (92, 'BACKSLASH'), (ord(']'), 'BRACKETR'),
         (ord("'"), 'APOSTROPHE'), (ord('/'), 'DIVIDE'), (ord('*'), 'TIMES'), (ord('+'), 'PLUS')]
# Mouse buttons, as the game numbers them (left, middle, right, wheel up, wheel down, X1, X2), stored at 2000+
mouse = [(2001, 'LMB'), (2002, 'MMB'), (2003, 'RMB'), (2004, 'MWHU'), (2005, 'MWHD'), (2006, 'MOUSE4'), (2007, 'MOUSE5')]
keys = [(code, name) for code, name in keys + mouse if (keys_src / (name + '.png')).exists()]

out_dir.mkdir(parents=True, exist_ok=True)
for set_name, prefix in pad_sets:
    atlas = Image.new('RGBA', (512, 256))
    for i, (_, name) in enumerate(pad_icons):
        im = Image.open(iv / (prefix + name + '.dds')).convert('RGBA').resize((64, 64), Image.LANCZOS)
        atlas.paste(im, ((i % 8) * 64, (i // 8) * 64))
    atlas.save(out_dir / ('pad_%s.png' % set_name), optimize=True)

cells, cell = [], 0
atlas = Image.new('RGBA', (1024, 1024))
pictures = {}
for code, name in keys:
    if name not in pictures:
        im = Image.open(keys_src / (name + '.png')).convert('RGBA')
        if im.height != 64:
            im = im.resize((round(im.width * 64 / im.height), 64), Image.LANCZOS)
        im = im.crop((0, 0, min(im.width, 128), 64))
        atlas.paste(im, ((cell % 8) * 128, (cell // 8) * 64))
        pictures[name] = (cell, im.width)
        cell += 1
    cells.append((code, name) + pictures[name])
atlas.save(out_dir / 'keys.png', optimize=True)

lines = ['#pragma once\n', '#include <cstdint>\n\n',
         '// Generated by resources/button-icons/generate.py. Do not edit.\n',
         '// Pad atlases: 512x256, 64x64 cells, 8 per row, in PadIcon order. Key atlas: 1024x1024, 128x64 cells, 8 per row.\n',
         'namespace RWGTA::ButtonIcons\n{\n',
         '    enum class PadIcon : uint8_t\n    {\n        ' + ', '.join(n for n, _ in pad_icons) + ',\n        Count\n    };\n\n',
         '    struct KeyPicture\n    {\n        uint16_t code;   // the game\'s key code; 2000 + n for mouse button n\n',
         '        uint8_t cell;\n        uint8_t width;   // of the picture in its 128x64 cell\n    };\n\n',
         '    inline constexpr KeyPicture KeyPictures[] =\n    {\n']
for code, name, c, w in cells:
    lines.append('        { %d, %d, %d }, // %s\n' % (code, c, w, name))
lines.append('    };\n}\n')
header.write_text(''.join(lines), encoding='utf-8', newline='\n')
print(len(pad_icons), 'pad icons,', len(cells), 'keys in', cell, 'cells')
