    inline bool Readable(const void* p, size_t size)
    {
        auto at = reinterpret_cast<uintptr_t>(p);
        if (!at || size > UINTPTR_MAX - at) return false;
        const auto end = at + size;
        while (at < end)
        {
            MEMORY_BASIC_INFORMATION info{};
            if (!VirtualQuery(reinterpret_cast<void*>(at), &info, sizeof(info)) || info.State != MEM_COMMIT ||
                (info.Protect & (PAGE_GUARD | PAGE_NOACCESS))) return false;
            const auto next = reinterpret_cast<uintptr_t>(info.BaseAddress) + info.RegionSize;
            if (next <= at) return false;
            at = next;
        }
        return true;
    }
    template<class T> inline std::optional<T> Read(const void* p, size_t offset)
    {
        if (!p || offset > UINTPTR_MAX - reinterpret_cast<uintptr_t>(p)) return {};
        const auto at = reinterpret_cast<const uint8_t*>(p) + offset;
        if (!Readable(at, sizeof(T))) return {};
        T value{}; std::memcpy(&value, at, sizeof(value)); return value;
    }
