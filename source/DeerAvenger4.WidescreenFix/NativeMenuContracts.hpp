    inline bool Supported()
    {
        const auto base = reinterpret_cast<uintptr_t>(GetModuleHandleW(nullptr));
        if (base != 0x400000 || !Readable(reinterpret_cast<void*>(base), sizeof(IMAGE_DOS_HEADER)))
            return false;
        const auto dos = Read<IMAGE_DOS_HEADER>(base);
        if (dos.e_magic != IMAGE_DOS_SIGNATURE || dos.e_lfanew <= 0 || dos.e_lfanew > 4096)
            return false;
        const auto ntAddress = base + static_cast<uintptr_t>(dos.e_lfanew);
        if (!Readable(reinterpret_cast<void*>(ntAddress), sizeof(IMAGE_NT_HEADERS32)))
            return false;
        const auto nt = Read<IMAGE_NT_HEADERS32>(ntAddress);
        if (nt.Signature != IMAGE_NT_SIGNATURE || nt.FileHeader.Machine != IMAGE_FILE_MACHINE_I386 ||
            nt.OptionalHeader.Magic != IMAGE_NT_OPTIONAL_HDR32_MAGIC ||
            nt.OptionalHeader.SizeOfImage != 0x243000 || nt.OptionalHeader.ImageBase != 0x400000)
            return false;
        for (const auto& prefix : prefixes)
            if (!Readable(reinterpret_cast<void*>(prefix.address), prefix.bytes.size()) ||
                std::memcmp(reinterpret_cast<void*>(prefix.address), prefix.bytes.data(), prefix.bytes.size()))
                return false;
        return true;
    }
