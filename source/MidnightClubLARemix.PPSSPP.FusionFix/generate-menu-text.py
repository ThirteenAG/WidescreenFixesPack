from pathlib import Path
import json, sys
# The game's menu font uses Latin-1; typographic punctuation maps to ASCII.
root = Path(__file__).resolve().parents[2]
keys = [
    ("Plugins", "menu.plugins"), ("Preset", "menu.preset"),
    ("Vanilla", "preset.vanilla"), ("Recommended", "preset.recommended"), ("Enhanced", "preset.enhanced"),
    ("Custom", "menu.custom"), ("On", "menu.on"), ("Off", "menu.off"), ("Auto", "auto"),
    ("Back", "menu.back"), ("Help", "menu.help"), ("Restart", "menu.restart"), ("SaveError", "menu.save.error"),
    ("PresetHelp", "menu.preset.help"),
]
for name in ["FOVFactor", "HudAspectRatioConstraint", "HUDScale", "CutsceneBorders", "SkipIntro", "DualAnalogPatch"]:
    keys.extend([(name, name), (name + "Help", name + ".description")])
for label in ["off", "letterbox", "pillarbox", "both"]:
    keys.append(("Borders" + label.title(), "borders." + label))
ascii = {"‘": "'", "’": "'", "“": '"', "”": '"', "–": "-", "—": "-", "…": "...", " ": " "}
def literal(text):
    data = "".join(ascii.get(c, c) for c in text).encode("latin-1")
    return '"' + "".join(chr(b) if 32 <= b < 127 and chr(b) not in '"\\' else "\\%03o" % b for b in data) + '"'
lines = ["#pragma once", "// Generated by generate-menu-text.py from the shipped text catalogs.", "namespace mc3::menu", "{",
         "enum class Word", "{"]
lines.extend("    " + name + "," for name, key in keys)
lines.extend(["    Count", "};", "inline constexpr const char* labels[5][unsigned(Word::Count)]", "{"])
for lang in ["en", "fr", "de", "it", "es"]:
    catalog = json.loads((root / "text/MCLARemix" / (lang + ".json")).read_text(encoding="utf-8"))
    lines.append("    {")
    lines.extend("        " + literal(catalog[key]) + "," for name, key in keys)
    lines.append("    },")
lines.extend(["};", "}", ""])
output = "\n".join(lines)
target = Path(__file__).with_name("MenuText.hpp")
if "--check" in sys.argv:
    if target.read_text(encoding="utf-8") != output:
        raise SystemExit("MenuText.hpp is stale; run generate-menu-text.py")
    print("Native menu text matches all five catalogs.")
else:
    target.write_text(output, encoding="utf-8", newline="\n")
