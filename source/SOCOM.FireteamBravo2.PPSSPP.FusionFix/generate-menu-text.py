from pathlib import Path
import argparse, json, sys
root = Path(__file__).resolve().parents[2]
keys = [
    ("Plugins", "menu.plugins"), ("Preset", "menu.preset"),
    ("Vanilla", "preset.vanilla"), ("Recommended", "preset.recommended"), ("Enhanced", "preset.enhanced"),
    ("On", "menu.on"), ("Off", "menu.off"), ("Auto", "auto"), ("Custom", "menu.custom"),
    ("Back", "menu.back"), ("Confirm", "menu.confirm"), ("Restart", "menu.restart"),
    ("SaveError", "menu.save.error"), ("Language", "language"), ("LanguageHelp", "language.description"),
    ("Help", "menu.help"), ("HelpButton", "menu.help.button"), ("PresetHelp", "menu.preset.help"),
]
for label in ["skip", "analog", "loading", "fov", "aspect", "hudaspect", "hudscale", "borders", "icons", "fps"]:
    name = label[0].upper() + label[1:]
    keys.extend([(name, label), (name + "Help", label + ".description")])
for label in ["off", "letterbox", "pillarbox", "both"]:
    keys.append(("Borders" + label.title(), "borders." + label))
lines = ["#pragma once", "// Generated by generate-menu-text.py from the shipped text catalogs.", "namespace NativeMenu", "{", "enum class Word", "{"]
lines.extend("    " + name + "," for name, key in keys)
lines.extend(["    Count", "};", "inline constexpr const char* labels[5][unsigned(Word::Count)]", "{"])
for lang in ["en", "fr", "de", "it", "es"]:
    catalog = json.loads((root / "text/SocomFTB2" / (lang + ".json")).read_text(encoding="utf-8"))
    lines.append("    {")
    # The menu font has no typographic apostrophe.
    lines.extend("        " + json.dumps(catalog[key].replace("’", "'"), ensure_ascii=False) + "," for name, key in keys)
    lines.append("    },")
lines.extend(["};", "}", ""])
output = "\n".join(lines)
target = Path(__file__).with_name("MenuText.hpp")
if "--check" in sys.argv:
    if target.read_text(encoding="utf-8") != output:
        raise SystemExit("MenuText.hpp is stale; run generate-menu-text.py")
    print("Native menu text matches all five catalogs.")
else:
    target.write_text(output, encoding="utf-8")
