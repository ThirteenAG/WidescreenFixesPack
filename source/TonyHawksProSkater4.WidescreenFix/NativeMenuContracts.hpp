    inline bool Readable(const void* value, size_t count)
    {
        auto at = reinterpret_cast<uintptr_t>(value);
        if (!at || count > UINTPTR_MAX - at) return false;
        const auto end = at + count;
        while (at < end)
        {
            MEMORY_BASIC_INFORMATION memory{};
            if (!VirtualQuery(reinterpret_cast<const void*>(at), &memory, sizeof(memory)) || memory.State != MEM_COMMIT || (memory.Protect & (PAGE_GUARD | PAGE_NOACCESS))) return false;
            if (!(memory.Protect & (PAGE_READONLY | PAGE_READWRITE | PAGE_WRITECOPY | PAGE_EXECUTE_READ | PAGE_EXECUTE_READWRITE | PAGE_EXECUTE_WRITECOPY))) return false;
            auto next = reinterpret_cast<uintptr_t>(memory.BaseAddress) + memory.RegionSize;
            if (next <= at) return false;
            at = next;
        }
        return true;
    }
    template<class T> T Read(const void* value, size_t offset = 0)
    {
        T result{};
        auto at = reinterpret_cast<uintptr_t>(value);
        if (offset > UINTPTR_MAX - at) return result;
        auto* field = reinterpret_cast<const void*>(at + offset);
        if (Readable(field, sizeof(result))) std::memcpy(&result, field, sizeof(result));
        return result;
    }
